
from django.contrib import admin

from .models import Analytics


@admin.register(Analytics)
class AnalyticsAdmin(admin.ModelAdmin):
    """
    Admin configuration for Analytics records.
    """

    list_display = (
        "id",
        "created_at",
        "updated_at",
        "resolved_at",
        "resolution_status",
    )

    list_filter = (
        "created_at",
        "updated_at",
        "resolved_at",
    )

    search_fields = (
        "id",
    )

    ordering = (
        "-created_at",
    )

    list_per_page = 25

    readonly_fields = (
        "id",
        "created_at",
        "updated_at",
        "resolved_at",
    )

    fieldsets = (
        (
            "Analytics Information",
            {
                "fields": (
                    "id",
                ),
            },
        ),
        (
            "Record Timestamps",
            {
                "fields": (
                    "created_at",
                    "updated_at",
                    "resolved_at",
                ),
            },
        ),
    )

    @admin.display(description="Resolution Status")
    def resolution_status(self, obj):
        return "Resolved" if obj.resolved_at else "Pending"

    def has_add_permission(self, request):
        # Analytics records should be generated by application logic.
        return False
